const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');

(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:path.join(process.env['ProgramFiles(x86)'],'Microsoft/Edge/Application/msedge.exe')});
  const records=[],errors=[];
  try{
    for(const width of [1440,390]){
      const page=await browser.newPage({viewport:{width,height:960},reducedMotion:'no-preference'});
      page.on('pageerror',error=>errors.push(error.message));
      await page.goto(process.env.BANK_UI_TEST_URL||'http://127.0.0.1:8138');
      await page.locator('#login-dialog[open]').waitFor();
      assert(!(await page.locator('#login-heading').evaluate(node=>getComputedStyle(node).fontFamily)).includes('Jianxing'));
      assert.equal(await page.locator('.login-submit').evaluate(node=>getComputedStyle(node,'::before').animationDuration),'2s');
      assert.equal(await page.locator('#workspace-edges').getAttribute('data-running'),'false');
      await page.locator('#login button[type=submit]').click();await page.waitForFunction(()=>window.accountUser?.username==='demo');
      await page.evaluate(()=>document.fonts.ready);await page.waitForTimeout(1400);
      const canvas=page.locator('#workspace-edges');
      await page.waitForFunction(()=>document.querySelector('#workspace-edges').dataset.running==='true'&&Number(document.querySelector('#workspace-edges').dataset.particles)>0);
      const pixels=()=>canvas.evaluate(node=>{const bytes=node.getContext('2d').getImageData(0,0,node.width,node.height).data;let sum=0;for(let i=3;i<bytes.length;i+=4)sum=(sum+bytes[i]*(i%97+1))%1000000007;return sum;});
      const firstPixels=await pixels(),start=Number(await canvas.getAttribute('data-frame'));
      await page.waitForTimeout(600);assert.notEqual(await pixels(),firstPixels);
      const frames=Number(await canvas.getAttribute('data-frame'))-start;assert(frames>0&&frames<28);
      assert(Number(await canvas.getAttribute('data-particles'))<=Number(await canvas.getAttribute('data-particle-limit')));
      const font=await page.locator('.message.assistant>div').first().evaluate(node=>getComputedStyle(node).fontFamily);
      assert(font.includes('Jianxing Text SC'));
      assert(await page.evaluate(()=>document.fonts.check('400 14px "Jianxing Text SC"','理财转账任务')));
      await page.screenshot({path:'.data/atelier-workspace-'+width+'.png',fullPage:true});
      await page.evaluate(async()=>{await api('/api/demo/payroll',{event_id:'atelier-'+crypto.randomUUID(),amount_fen:450000});await overview();});
      await page.locator('#input').fill('给妈妈转400元，给小王转1500元，剩下的钱20%用于理财并推荐');await page.locator('#send').click();
      await page.waitForFunction(()=>!document.querySelector('#send').disabled&&plan?.nodes?.filter(n=>n.operation==='funds.transfer').length===2);
      const card=page.locator('article[data-node-id]').filter({hasText:'妈妈'});
      await card.getByRole('button',{name:'核对并确认',exact:true}).click();
      await page.locator('#detail-dialog[open]').waitFor();
      await page.waitForFunction(()=>document.querySelector('#workspace-edges').dataset.running==='false');
      assert.equal(await canvas.getAttribute('data-running'),'false');
      await page.getByRole('button',{name:'确认办理本步骤',exact:true}).click();
      await page.waitForFunction(()=>plan.nodes.some(n=>n.operation==='funds.transfer'&&n.status==='SUCCEEDED'));
      assert(await page.locator('.goal-heading .goal-status').count());
      await page.locator('.request-goals').screenshot({path:'.data/atelier-goals-'+width+'.png'});
      await card.screenshot({path:'.data/atelier-transaction-'+width+'.png'});
      assert.equal(await card.locator('.node-result-detail>summary').evaluate(node=>getComputedStyle(node).fontSize),'12px');
      await page.locator('#model').click();
      await page.locator('.research-form textarea').fill('核查收支与理财风险和流动性，只分析不办理。');
      await page.locator('.research-check input').check();await page.locator('.research-form button[type=submit]').click();
      await page.locator('#research-status').filter({hasText:'分析完成'}).waitFor({timeout:30000});
      await page.evaluate(()=>document.fonts.ready);
      const cdp=await page.context().newCDPSession(page);await cdp.send('DOM.enable');await cdp.send('CSS.enable');
      const dom=await cdp.send('DOM.getDocument'),match=await cdp.send('DOM.querySelector',{nodeId:dom.root.nodeId,selector:'.research-summary'});
      const fonts=await cdp.send('CSS.getPlatformFontsForNode',{nodeId:match.nodeId});
      assert(fonts.fonts.some(font=>font.isCustomFont&&font.familyName.includes('Jianxing Text')));
      await page.locator('.research-overview').screenshot({path:'.data/atelier-research-'+width+'.png'});
      assert(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth));
      await page.locator('#ambient-toggle').click();
      await page.waitForFunction(()=>document.querySelector('#workspace-edges').dataset.running==='false');
      const stopped=await canvas.getAttribute('data-frame');await page.waitForTimeout(250);assert.equal(await canvas.getAttribute('data-frame'),stopped);
      assert.equal(await pixels(),0);
      await page.reload();await page.waitForFunction(()=>window.accountUser?.username==='demo');
      assert.equal(await page.locator('#ambient-toggle').getAttribute('aria-pressed'),'false');
      await page.locator('#ambient-toggle').click();await page.waitForFunction(()=>document.querySelector('#workspace-edges').dataset.running==='true');
      await page.emulateMedia({reducedMotion:'reduce'});
      await page.waitForFunction(()=>document.querySelector('#ambient-toggle').disabled);
      assert(await page.locator('#ambient-toggle').isDisabled());
      assert.equal(await page.locator('#workspace-edges').getAttribute('data-running'),'false');
      records.push({width,actualParticlePixels:true,frameCap:true,particleCap:true,modalPause:true,customChineseFont:true,goalTypography:true,noHorizontalOverflow:true,togglePersists:true,reducedMotion:true,loginPreserved:true});
      await page.close();
    }
    assert.deepEqual(errors,[]);
    fs.writeFileSync('.data/workspace-ui-results.json',JSON.stringify({at:new Date().toISOString(),records,javascriptErrors:errors},null,2));
    console.log(JSON.stringify(records));
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
