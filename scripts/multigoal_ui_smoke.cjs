const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');

(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:path.join(process.env['ProgramFiles(x86)'],'Microsoft/Edge/Application/msedge.exe')});
  const records=[];
  try{
    const page=await browser.newPage({viewport:{width:1440,height:1050}}),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.goto(process.env.BANK_UI_TEST_URL||'http://127.0.0.1:8131');
    await page.locator('#login button[type=submit]').click();
    await page.waitForFunction(()=>window.accountUser?.username==='demo');
    await page.evaluate(async()=>{await api('/api/demo/payroll',{event_id:'multigoal-ui-'+crypto.randomUUID(),amount_fen:450000});await overview();});
    const before=await page.evaluate(()=>facts.account.balance_fen);
    await page.locator('#input').fill('给妈妈转400元，给小王转1500元，剩下的钱20%用于理财，并给出推荐');
    await page.locator('#send').click();
    await page.waitForFunction(()=>!document.querySelector('#send').disabled&&plan?.nodes.filter(n=>n.operation==='funds.transfer').length===2);
    const original=await page.evaluate(()=>plan.id);
    assert.equal(await page.evaluate(()=>facts.account.balance_fen),before);
    const first=page.locator('article[data-node-id]').filter({hasText:'妈妈'});
    await first.getByRole('button',{name:'核对并确认',exact:true}).click();
    await page.getByRole('button',{name:'确认办理本步骤',exact:true}).click();
    await page.waitForFunction(()=>plan.nodes.filter(n=>n.operation==='funds.transfer'&&n.status==='SUCCEEDED').length===1&&!document.querySelector('#detail-dialog').open);
    const second=page.locator('article[data-node-id]').filter({hasText:'小王'});
    await second.getByRole('button',{name:'核对并验证',exact:true}).click();
    await page.locator('#detail-dialog').getByRole('button',{name:'获取演示验证码',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#detail-dialog input[autocomplete="one-time-code"]')?.value.length===6);
    await page.getByRole('button',{name:'验证并办理本步骤',exact:true}).click();
    await page.waitForFunction(()=>plan.nodes.filter(n=>n.operation==='funds.transfer'&&n.status==='SUCCEEDED').length===2&&!document.querySelector('#detail-dialog').open);
    const receipts=await page.evaluate(()=>plan.nodes.filter(n=>n.operation==='funds.transfer').map(n=>n.result.receipt_id));
    assert.equal(await page.evaluate(()=>facts.account.balance_fen),before-190000);
    await page.getByRole('button',{name:'选择模拟30天产品',exact:true}).click();
    await page.locator('#detail-dialog[open] .risk-question select').first().waitFor();
    assert((await page.locator('#detail-title').innerText()).includes('风险测评'));
    assert.equal(await page.locator('.risk-question select').count(),5);
    await page.screenshot({path:'.data/multigoal-auto-assessment.png',fullPage:true});
    for(const question of await page.locator('.risk-question select').all())await question.selectOption('3');
    await page.locator('#detail-content form button[type=submit]').click();
    await page.waitForFunction(()=>plan?.nodes?.some(n=>n.operation==='wealth.assess'&&n.status==='WAIT_CONFIRM')&&!document.querySelector('#detail-dialog').open);
    await page.reload();
    await page.waitForFunction(()=>window.accountUser?.username==='demo'&&plan?.nodes?.some(n=>n.operation==='wealth.assess'&&n.status==='WAIT_CONFIRM'));
    await page.locator('article[data-node-id]').filter({hasText:'更新模拟风险测评'}).getByRole('button',{name:'核对并确认',exact:true}).click();
    await page.getByRole('button',{name:'确认办理本步骤',exact:true}).click();
    await page.waitForFunction(id=>plan?.id===id&&plan.nodes.some(n=>n.operation==='wealth.purchase'&&n.status==='WAIT_MFA')&&!document.querySelector('#detail-dialog').open,original);
    assert.deepEqual(await page.evaluate(()=>plan.nodes.filter(n=>n.operation==='funds.transfer').map(n=>n.result.receipt_id)),receipts);
    assert.equal(await page.evaluate(()=>facts.account.balance_fen),before-190000);
    assert.equal(await page.evaluate(()=>plan.nodes.find(n=>n.operation==='wealth.purchase').params.amount_fen),Math.floor((before-190000)*.2));
    await page.locator('#model').click();
    await page.locator('.research-form textarea').fill('只分析本月账单与理财风险和流动性，不生成办理方案。');
    await page.locator('.research-check input').check();
    await page.locator('.research-form button[type=submit]').click();
    await page.locator('#research-status').filter({hasText:'分析完成'}).waitFor({timeout:30000});
    assert.equal(await page.locator('.research-metrics>div').count(),4);
    assert.equal(await page.locator('.research-role[open]').count(),0);
    assert(await page.evaluate(()=>!!(document.querySelector('#plan-panel').compareDocumentPosition(document.querySelector('#research-panel'))&Node.DOCUMENT_POSITION_FOLLOWING)));
    assert.equal(await page.locator('.research-product').count(),3);
    await page.locator('.research-role').first().locator('summary').first().click();
    assert(await page.locator('.research-finding h4').first().isVisible());
    await page.locator('.research-role').first().locator('summary').first().click();
    await page.getByRole('button',{name:'收起报告',exact:true}).click();
    assert(await page.locator('#research-content').isHidden());
    await page.getByRole('button',{name:'展开报告',exact:true}).click();
    for(const width of [1440,390]){
      await page.setViewportSize({width,height:1050});
      await page.locator('#research-panel').scrollIntoViewIfNeeded();
      assert(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth));
      await page.screenshot({path:'.data/multigoal-research-'+width+'.png',fullPage:true});
      await page.locator('#research-panel').screenshot({path:'.data/multigoal-report-panel-'+width+'.png'});
      records.push({width,multipleTransfers:true,confirmationAndMfa:true,automaticAssessment:true,prerequisiteReload:true,returnToOriginalPlan:true,noDuplicateTransfer:true,structuredResearch:true,noOverflow:true});
    }
    assert.deepEqual(errors,[]);
    fs.writeFileSync('.data/multigoal-ui-results.json',JSON.stringify({at:new Date().toISOString(),records},null,2));
    console.log(JSON.stringify(records));
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
