"""Blind, bounded scoring packets from actual observed output and independent references."""
import json
from decimal import Decimal
from pathlib import Path
import re

from .judge_schemas import Criterion, Evidence, JudgePacket
from .trace import scrub

PLAN_UI_PACKET_VERSION = "plan-ui-v3"
PLAN_UI_SUFFIX = "_plan_ui_v3"


def build_packet(case, result, plan_ui=False, browser=None):
    ui = (Path(__file__).resolve().parents[1] / "bank_agent/static/ui.js").read_text(encoding="utf-8") if plan_ui else ""
    def labels(name):
        match = re.search(r"export const " + name + r" = \{(.*?)\};", ui, re.S)
        return {
            a or b: value for a, b, value in re.findall(r"(?:'([^']+)'|([A-Z_]+)):'([^']+)'", match.group(1))} if match else {}
    states, operations = labels("states"), labels("operations")
    def presentation(response):
        preview = response.get("funding_preview")
        view = {"界面状态": states.get(response.get("status"), response.get("status")),
                "界面办理步骤": [{"业务": operations.get(n["operation"], "办理步骤"),
                    "状态": states.get(n["status"], n["status"]), "权限级别": n["tier"],
                    "金额（元）": format(Decimal(n["params"]["amount_fen"]) / 100, ".2f") if isinstance(n["params"].get("amount_fen"), int) else None}
                    for n in response.get("nodes", [])]}
        if preview:
            def money(fields):
                return {k.removesuffix("_fen"): format(Decimal(v) / 100, ".2f") for k, v in fields.items() if k.endswith("_fen") and isinstance(v, int)}
            view["界面资金预览（元）"] = {"当前": money(preview.get("before", {})), "预计办理后": money(preview.get("after", {})),
                "本次需要": format(Decimal(preview["required_fen"]) / 100, ".2f"), "缺口": format(Decimal(preview["shortfall_fen"]) / 100, ".2f")}
        batch = response.get("confirmation_batch", {})
        if batch.get("available"):
            view["界面集中确认"] = [{"业务": operations.get(n["operation"], "办理步骤"), "权限级别": n["tier"]} for n in batch["items"]]
        return view
    rendered, cursor = [], -1
    events = result.get("trace", [])
    confirmations = [(i, e["response"]) for i, e in enumerate(events) if e.get("kind") == "api"
                     and e.get("status") == 200 and e.get("path", "").endswith(("/approve", "/approve-batch"))]
    for turn in result.get("responses", []):
        response = turn["response"]
        if plan_ui:
            anchor = turn.get("trace_event_index")
            if anchor is not None:
                anchor -= 1
            elif response.get("nodes"):
                # Older episodes did not record a capture cursor. Bind the
                # actual matching API snapshot, not a guessed timestamp/order.
                anchor = next((i for i, e in enumerate(events) if i > cursor and e.get("kind") == "api"
                    and all(e.get("response", {}).get(k) == response.get(k) for k in ("id", "status", "version", "nodes"))), None)
            if anchor is not None:
                for i, snapshot in confirmations:
                    if cursor < i < anchor:
                        rendered.append({"实际确认后的界面更新": presentation(snapshot)})
                cursor = anchor
        item = {"轮次": turn["label"]}
        if turn["user_text"]:
            item["用户"] = turn["user_text"]
        for field in ("message", "assistant_message", "summary", "status"):
            if response.get(field):
                item[{"message": "回复", "assistant_message": "业务回复", "summary": "计划摘要", "status": "状态"}[field]] = response[field]
        if plan_ui:
            item.update(presentation(response))
        report = response.get("report")
        if report:
            item["研究结果"] = {"summary": report.get("summary"), "constraints": report.get("constraints"),
                "funding": report.get("funding"), "findings": [{"text": c["text"], "kind": c["kind"]}
                for c in report.get("findings", [])], "products": [{"name": p["name"], "excluded": p["excluded"],
                "reasons": p["reasons"]} for p in report.get("products", [])], "gaps": report.get("gaps", [])}
        node_results = []
        for node in response.get("nodes", []):
            if node.get("error"):
                node_results.append({"业务说明": node["error"].get("message"), "下一步": node["error"].get("next_step")})
            if node.get("result"):
                # These are returned result facts, not new prose generated by the runner.
                data = node["result"]["data"]
                data = {k: v for k, v in data.items() if k not in {"transaction_id", "receipt_id", "transaction_ids", "request_id",
                    "source", "evidence_ids", "hold_id", "goal_id", "order_id", "method", "category_method"}}
                node_results.append({"接口返回的展示数据": scrub(data)})
        if node_results:
            item["业务结果"] = node_results
        if response.get("error"):
            item["接口错误"] = response["error"]
        rendered.append(item)
    if browser is not None:
        unique = {}
        for frame in browser["frames"]:
            key = (frame["visible_text"], tuple(frame["buttons"]))
            if key not in unique:
                unique[key] = {"可见文字": frame["visible_text"], "可见按钮": frame["buttons"], "视口宽度": []}
            unique[key]["视口宽度"].append(frame["width"])
        rendered = list(unique.values())
    if not rendered:
        rendered = [{"评测事实": "被测系统没有返回有效的业务响应", "错误": result.get("sut_error")}]
    candidate = json.dumps(rendered, ensure_ascii=False, sort_keys=True)
    # Do not silently truncate the candidate and then report completeness scores.
    if len(candidate) > 30000:
        raise ValueError("JUDGE_PACKET_TOO_LARGE")
    initial = {"balance_fen": case.balance_fen, "risk_level": case.risk_level, "risk_valid_until": case.risk_valid_until,
               "business_date": "2026-10-13", "fixture_changes": case.patches}
    evidence_version = result.get("manifest_hash") or "standalone-development"
    evidence = [Evidence(id="initial_bank", authority="bank_snapshot", version=evidence_version,
                         text=json.dumps(initial, ensure_ascii=False)),
                Evidence(id="gold_outcomes", authority="independent_gold", version=evidence_version,
                         text=json.dumps([c.model_dump(mode="json") for c in case.checks], ensure_ascii=False)),
                Evidence(id="measured_outcomes", authority="bank_snapshot", version="episode-final",
                    text=json.dumps({k: result.get("state", {}).get(k) for k in ["balance_fen", "reserved_fen", "available_fen",
                    "receipts", "node_errors", "users", "financial_unchanged", "authorization_tiers"]}, ensure_ascii=False))]
    if result.get("observations"):
        report = next((o["report"] for o in result["observations"].values() if o.get("report")), None)
        if report:
            for source in report.get("evidence", []):
                text = json.dumps({"tool": source["tool"], "data": source["data"]}, ensure_ascii=False)
                if len(text) > 10000:
                    # Full raw rows remain in the episode. Judge gets a labelled relevant
                    # excerpt; deterministic raw-source checks are not weakened.
                    if source["tool"] == "transaction_details":
                        rows = source["data"]["rows"]
                        period = report.get("constraints", {}).get("period")
                        relevant = [r for r in rows if not period or str(r.get("posted_at", "")).startswith(period)]
                        text = json.dumps({"tool": source["tool"], "data": {"rows": relevant[:25],
                            "excerpt_only": True, "full_row_count": len(rows), "period_filter": period,
                            "matching_row_count": len(relevant), "shown_row_count": min(25, len(relevant)),
                            "selection_policy": "source order within requested period; first 25; omissions cannot prove absence"}}, ensure_ascii=False)
                    else:
                        raise ValueError("JUDGE_EVIDENCE_TOO_LARGE")
                authority = "product_disclosure" if source["authority"] == "synthetic_disclosure" else (
                    "user_declared" if source["authority"] == "user_declared" else "bank_snapshot")
                evidence.append(Evidence(id=source["id"], authority=authority, version=source["version"], text=text))
    return JudgePacket(case_id=case.id, user_goal="；".join(s.text for s in case.steps if s.text) or case.title,
        expected_behavior=case.expected_behavior, candidate_output=candidate, evidence=evidence,
        criteria=[Criterion(id=f"criterion_{i+1}", text=t, critical=False) for i, t in enumerate(case.criteria)])
